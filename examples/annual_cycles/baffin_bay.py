def mld_deltarho(ds, rho="rho", z="z", deltarho=0.1):
    idx = (ds[rho] - ds[rho].isel({z: 0}) > deltarho).argmax(z)
    mld = ds[z].isel({z: idx}).rename("mld").drop_vars(z)
    return mld


def add_ustar0(df):
    """
    Based on ice concentration and 10-m wind speed, add ocean-side ustar0 to dataframe.
    """

    def large_pond_1981(U10):
        """
        Large and Pond 1981
        """
        return np.where(
            U10 < 11,
            1.2e-3,
            (0.49 + 0.065 * U10) * 1e-3,
        )

    Ca_dct = {
        "MIZ": 4e-3,
        "summer_packice": 2.1e-3,
        "winter_packice": 4e-3,  # ??
        "open_water": large_pond_1981,
    }

    def determine_ice_type(df):
        if df.ice <= 15:
            return "open_water"
        elif df.ice <= 80:
            return "MIZ"
        elif df.doy <= 150 or df.doy >= 320:
            return "winter_packice"
        else:
            return "summer_packice"

    df["icetype"] = df.apply(determine_ice_type, axis=1)

    def determine_Ca(df):
        Ca = Ca_dct[df.icetype]
        if callable(Ca):
            return Ca(df.loc["windspeed10"])
        else:
            return Ca

    df["Ca"] = df.apply(determine_Ca, axis=1).astype(float)
    df["ustar0"] = (
        df.Ca * df.windspeed10**2 * 1 / 1000.0
    ) ** 0.5  # multiply by rho_air/rho_water

    return df


def format_forcing(df):
    df = df.rename(columns={"doy": "time", "heatflux": "qcond", "ice": "sic"})
    df = df.sort_values("time", ignore_index=True)
    return df


def get_forcing():
    from examples.annual_cycles.data.baffin import forcing as forcing_df

    forcing_df = add_ustar0(forcing_df)
    forcing_df = format_forcing(forcing_df)
    return forcing_df


def get_ctd(forcing_df):
    from examples.annual_cycles.data.baffin import ctd

    t0 = ctd.time.values[0]

    ctd = ctd.interp({"time": forcing_df.time})
    ctd = ctd.isel(time=ctd.time >= t0, Depth=ctd.Depth <= 100)
    return ctd


class VariableBoundaryLayer(SteadyLTCModel):
    """
    A model that can switch between ice cover and open water.
    """

    sic = param.Number(default=100, bounds=(0, 100), doc="Sea ice conc. (%)")

    def update_interface(self, **kwarg):
        if self.sic <= 15:
            # open water
            self.S0 = self.S[0]
            self.T0 = self.T[0]
            alpha = gsw.alpha(self.S0, self.T0, self.zz[0])
            self.wb0 = -alpha * self.qcond
            self.wT0 = self.qcond
            self.wS0 = 0
        else:
            # ice-covered
            SteadyLTCModel.update_interface(self, **kwarg)


def setup_scenario(ctd_init, forcing_df, duration=None, watch_param_set_events=True):
    """
    Setup a scenario. Will run for either `duration` (in days) or until
    the end of the forcing data.
    """

    start_time = ctd_init.time.values[()]

    state = VariableBoundaryLayer.from_ctd(
        time=start_time,
        latitude=73,
        SA=ctd_init["Salinity"],
        CT=ctd_init["Temperature"],
        zz=ctd_init["Depth"],
        z0=0.049,
        Sice=4,
        hice=2,  # not important - will force with sea ice concentration
        ustar0=1e-3,  # will be set by forcing
        wb0=0,  # initial guess
        adjustments=[get_transfer_coefficients],
        cht=0.0093,
        chs=0.0057,
        params_dynamic=["Uice", "wb0"],
        # do not watch parameter events -
        # reduces the overhead a lot (see run.cprof generated by test_baffin_bay.py)
        watch_param_set_events=watch_param_set_events,
    )

    forcing = Forcing(**forcing_df[["time", "ustar0", "qcond", "sic"]])

    stepper = TempSalStepper(
        state=state,
        forcing=forcing,
        deltat=6,
        leapfrog_smoother=0.1,
    )

    state.steady_ltc()
    state.init_leapfrog()

    scenario = ModelRun(
        stepper=stepper,
        write_output_step=1,
        duration=(
            (forcing.time.max() - start_time - 1) if duration is None else duration
        ),
    )
    return scenario


def run(scenario):
    with param.logging_level("WARNING"):
        scenario.execute()


def plot(ds, ctd):

    qcond_mld = (
        ds.qcond.hvplot.area(title="Upward ocean-to-atmosphere heat flux")
        + ds.mld.hvplot(label="Modelled", title="Mixed layer depth")
        # * mld_deltarho(ds, z="zz").hvplot()
        * mld_deltarho(ctd, rho="Density", z="Depth").hvplot(label="Observed")
    )
    ts = (
        ctd.Salinity.hvplot.quadmesh(title="Observed salinity")
        + ctd.Temperature.hvplot.quadmesh(clim=(-2, 5), title="Observed temperature")
        + ds.S.hvplot.quadmesh(title="Modelled salinity")
        + ds.T.hvplot.quadmesh(clim=(-2, 5), title="Modelled temperature")
    )
    l = qcond_mld + ts.apply.opts(cmap="viridis")

    plot_opts = dict(
        invert_yaxis=True,
        invert_axes=True,
        frame_width=250,
        frame_height=400,
    )
    return l.cols(2).opts(
        hv.opts.Area(**plot_opts),
        hv.opts.Curve(**plot_opts),
        hv.opts.QuadMesh(**plot_opts),
    )


if __name__ == "__main__":
    forcing_df = get_forcing()
    ctd = get_ctd(forcing_df)
    scenario = setup_scenario(ctd.isel(time=0), forcing_df, watch_param_set_events=False)
    run(scenario)

    Path("out/examples/baffin_bay").mkdir(parents=True, exist_ok=True)
    hv.save(plot(scenario.states, ctd), "out/examples/baffin_bay/scenario.html")
